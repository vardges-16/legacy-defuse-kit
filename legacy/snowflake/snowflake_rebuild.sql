-- =====================================================================
-- PART 4: checks (run each SELECT on its own)
-- =====================================================================
SELECT 'COST.FOCUS_COST' AS T, COUNT(*) AS ROWS_, SUM(TRY_TO_DOUBLE(BILLEDCOST)) AS AMOUNT, COUNT(DISTINCT _SOURCE_FILE) AS FILES FROM ZONTIQUE_LEGACY.COST.FOCUS_COST
UNION ALL SELECT 'CMDB.ASSETS', COUNT(*), NULL, COUNT(DISTINCT _SOURCE_FILE) FROM ZONTIQUE_LEGACY.CMDB.ASSETS
UNION ALL SELECT 'CMDB.ASSET_GROUPS', COUNT(*), NULL, COUNT(DISTINCT _SOURCE_FILE) FROM ZONTIQUE_LEGACY.CMDB.ASSET_GROUPS
UNION ALL SELECT 'FIN.BUDGET', COUNT(*), SUM(TRY_TO_DOUBLE(BUDGET_COST)), COUNT(DISTINCT _SOURCE_FILE) FROM ZONTIQUE_LEGACY.FIN.BUDGET
UNION ALL SELECT 'VMB.BACKUP_JOBS', COUNT(*), NULL, COUNT(DISTINCT _SOURCE_FILE) FROM ZONTIQUE_LEGACY.VMB.BACKUP_JOBS
UNION ALL SELECT 'VMB.BACKUP_STORAGE', COUNT(*), SUM(TRY_TO_DOUBLE(STORAGE_COST_USD)), COUNT(DISTINCT _SOURCE_FILE) FROM ZONTIQUE_LEGACY.VMB.BACKUP_STORAGE
UNION ALL SELECT 'RPT.V_COST_BY_APP', COUNT(*), SUM(TOTAL_COST_USD), NULL FROM ZONTIQUE_LEGACY.RPT.V_COST_BY_APP
UNION ALL SELECT 'RPT.V_BACKUP_COST_BY_VM', COUNT(*), SUM(STORAGE_COST_USD), NULL FROM ZONTIQUE_LEGACY.RPT.V_BACKUP_COST_BY_VM;

SELECT LEFT(CHARGEPERIODSTART, 7) AS MONTH, _SOURCE_FILE, COUNT(*) AS ROWS_, SUM(TRY_TO_DOUBLE(BILLEDCOST)) AS BILLED
FROM ZONTIQUE_LEGACY.COST.FOCUS_COST GROUP BY 1, 2 ORDER BY 1, 2;
