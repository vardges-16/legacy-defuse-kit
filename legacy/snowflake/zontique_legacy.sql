-- =====================================================================
-- PART 3: legacy reporting logic (RPT). How the old company reported; flawed on purpose.
-- =====================================================================
-- 3.1 hand-made application -> cost center map ("Finance Excel, 2023"): 5 apps missing,
--     E-Commerce on the wrong cost center, General Ledger on closed cost center 0999
CREATE TABLE ZONTIQUE_LEGACY.RPT.APP_COST_CENTER_MAP (SOLUTION_ID VARCHAR, COST_CENTER_CODE VARCHAR) AS
SELECT * FROM VALUES
  ('MFGEXE','0410'), ('PLMNT','0420'), ('QMSYS','0450'), ('DMDPLN','0610'), ('SUPPRT','0650'),
  ('SLSCRM','2110'), ('ECOMM','2150'), ('MKTAUT','2310'), ('ITSMGT','3110'), ('ENDPT','3120'),
  ('PLAT','3150'), ('EDPLAT','3170'), ('BILL','3510'), ('HRPORT','3550'), ('GLEDG','0999');

-- 3.2 cost by application: exact 'application' tag only (untagged, variant keys and GCP lower-case labels
--     are invisible), BilledCost (reservations land in the purchase month), month = first 7 characters
CREATE VIEW ZONTIQUE_LEGACY.RPT.V_COST_BY_APP AS
SELECT TRY_PARSE_JSON(TAGS):application::STRING AS SOLUTION_ID,
       LEFT(CHARGEPERIODSTART, 7)               AS USAGE_MONTH,
       SUM(TRY_TO_DOUBLE(BILLEDCOST))           AS TOTAL_COST_USD
FROM ZONTIQUE_LEGACY.COST.FOCUS_COST
WHERE TRY_PARSE_JSON(TAGS):application IS NOT NULL
GROUP BY 1, 2;

-- 3.3 budget, typed (rows with other date formats get a NULL month)
CREATE VIEW ZONTIQUE_LEGACY.RPT.V_BUDGET AS
SELECT BUSINESS_UNIT_NAME, DEPARTMENT_NAME, COST_CENTER_CODE, COST_CENTER_NAME,
       TRY_TO_NUMBER(FISCAL_YEAR) AS FISCAL_YEAR, TRY_TO_DATE(BUDGET_MONTH) AS BUDGET_MONTH,
       TRY_TO_DOUBLE(BUDGET_COST) AS BUDGET_COST
FROM ZONTIQUE_LEGACY.FIN.BUDGET;

-- 3.4 budget vs actual: actual only through the hand-made map; latest month only; duplicates summed;
--     all fiscal years added together and divided by 12 (fiscal year never checked)
CREATE VIEW ZONTIQUE_LEGACY.RPT.V_BUDGET_VS_ACTUAL AS
WITH bud AS (
  SELECT COST_CENTER_CODE, COST_CENTER_NAME, SUM(BUDGET_COST) / 12 AS MONTHLY_BUDGET_USD
  FROM ZONTIQUE_LEGACY.RPT.V_BUDGET GROUP BY 1, 2),
act AS (
  SELECT m.COST_CENTER_CODE, SUM(c.TOTAL_COST_USD) AS ACTUAL_USD
  FROM ZONTIQUE_LEGACY.RPT.V_COST_BY_APP c
  JOIN ZONTIQUE_LEGACY.RPT.APP_COST_CENTER_MAP m ON m.SOLUTION_ID = c.SOLUTION_ID
  WHERE c.USAGE_MONTH = (SELECT MAX(USAGE_MONTH) FROM ZONTIQUE_LEGACY.RPT.V_COST_BY_APP WHERE USAGE_MONTH LIKE '20%')
  GROUP BY 1)
SELECT b.COST_CENTER_CODE, b.COST_CENTER_NAME, b.MONTHLY_BUDGET_USD,
       COALESCE(a.ACTUAL_USD, 0) AS ACTUAL_USD, COALESCE(a.ACTUAL_USD, 0) - b.MONTHLY_BUDGET_USD AS VARIANCE_USD
FROM bud b LEFT JOIN act a ON a.COST_CENTER_CODE = b.COST_CENTER_CODE;

-- 3.5 resource group owners: Azure only, inner joins (unmapped and stale groups silently drop out)
CREATE VIEW ZONTIQUE_LEGACY.RPT.V_RG_OWNERS AS
SELECT rg.ASSET_NAME AS RESOURCE_GROUP, rg.ENVIRONMENT, app.ASSET_NAME AS APPLICATION,
       app.APPLICATION_CODE, app.DEPARTMENT, app.COST_CENTER
FROM ZONTIQUE_LEGACY.CMDB.ASSETS rg
JOIN ZONTIQUE_LEGACY.CMDB.ASSET_GROUPS g ON g.ASSET_GROUP_ID = rg.ASSET_GROUP_ID
JOIN ZONTIQUE_LEGACY.CMDB.ASSETS app ON app.ASSET_ID = g.APPLICATION_ASSET_ID
WHERE rg.ASSET_TYPE = 'AzureResourceGroup';

