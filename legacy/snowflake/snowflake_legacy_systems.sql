-- 5.1 Hand-made mapping application -> cost center ("Finance Excel, 2023"): 14 of 24
--     applications, one mapped to closed cost center 0999
CREATE OR REPLACE TABLE ZONTIQUE_LEGACY.RPT.APP_COST_CENTER_MAP (SOLUTION_ID VARCHAR, COST_CENTER_CODE VARCHAR) AS
SELECT * FROM VALUES
  ('SOL-03740087954b','3150'), ('SOL-e3c95e352780','3170'), ('SOL-35ab1cde6979','0610'),
  ('SOL-b96d469ca197','2110'), ('SOL-e279d76c5f8c','3120'), ('SOL-a7afd645143d','0410'),
  ('SOL-21b48693a79e','3510'), ('SOL-6bbf0af53bea','2310'), ('SOL-90834fec6443','3110'),
  ('SOL-e9a220bd9a9e','0450'), ('SOL-7667ac3c69e6','0999'), ('SOL-c3ffa9fe7783','3550'),
  ('SOL-4a5283a4a6a5','2150'), ('SOL-833aa614079e','0650');

-- 5.2 Cost by application. Flaw: tag-only attribution (untagged cost invisible), BilledCost.
CREATE OR REPLACE VIEW ZONTIQUE_LEGACY.RPT.V_COST_BY_APP AS
SELECT TRY_PARSE_JSON(TAGS::VARCHAR):SolutionId::STRING AS SOLUTION_ID,
       LEFT(CHARGEPERIODSTART, 7)                       AS USAGE_MONTH,
       SUM(TRY_TO_DOUBLE(BILLEDCOST))                   AS TOTAL_COST_USD
FROM ZONTIQUE_LEGACY.COST.FOCUS_COST
WHERE TRY_PARSE_JSON(TAGS::VARCHAR):SolutionId IS NOT NULL
GROUP BY 1, 2;

-- 5.3 Budget, typed. Read by the legacy report.
CREATE OR REPLACE VIEW ZONTIQUE_LEGACY.RPT.V_BUDGET AS
SELECT BUSINESS_UNIT_NAME, DEPARTMENT_NAME, COST_CENTER_CODE, COST_CENTER_NAME,
       TRY_TO_NUMBER(FISCAL_YEAR) AS FISCAL_YEAR, TRY_TO_DATE(BUDGET_MONTH) AS BUDGET_MONTH,
       TRY_TO_DOUBLE(BUDGET_COST) AS BUDGET_COST
FROM ZONTIQUE_LEGACY.FIN.BUDGET;

-- 5.4 Budget vs actual by cost center. Flaws: actual comes through the hand-made map
--     (unmapped applications and closed cost center 0999 vanish), and the latest cost month
--     is compared with an average budget month without checking that the years match.
CREATE OR REPLACE VIEW ZONTIQUE_LEGACY.RPT.V_BUDGET_VS_ACTUAL AS
WITH bud AS (
  SELECT COST_CENTER_CODE, COST_CENTER_NAME, SUM(BUDGET_COST) / COUNT(DISTINCT BUDGET_MONTH) AS MONTHLY_BUDGET_USD
  FROM ZONTIQUE_LEGACY.RPT.V_BUDGET GROUP BY 1, 2),
act AS (
  SELECT m.COST_CENTER_CODE, SUM(c.TOTAL_COST_USD) AS ACTUAL_USD
  FROM ZONTIQUE_LEGACY.RPT.V_COST_BY_APP c
  JOIN ZONTIQUE_LEGACY.RPT.APP_COST_CENTER_MAP m ON m.SOLUTION_ID = c.SOLUTION_ID
  WHERE c.USAGE_MONTH = (SELECT MAX(USAGE_MONTH) FROM ZONTIQUE_LEGACY.RPT.V_COST_BY_APP)
  GROUP BY 1)
SELECT b.COST_CENTER_CODE, b.COST_CENTER_NAME, b.MONTHLY_BUDGET_USD,
       COALESCE(a.ACTUAL_USD, 0) AS ACTUAL_USD,
       COALESCE(a.ACTUAL_USD, 0) - b.MONTHLY_BUDGET_USD AS VARIANCE_USD
FROM bud b LEFT JOIN act a ON a.COST_CENTER_CODE = b.COST_CENTER_CODE;

-- 5.5 Backup cost by VM. Flaws: only PROTECTION_STATE = 'Protected' (orphaned backups of
--     deleted VMs are invisible), and VM names are not normalized (one VM can appear twice).
CREATE OR REPLACE VIEW ZONTIQUE_LEGACY.RPT.V_BACKUP_COST_BY_VM AS
SELECT MONTH, VM_NAME, SUM(TRY_TO_DOUBLE(STORAGE_COST_USD)) AS STORAGE_COST_USD
FROM ZONTIQUE_LEGACY.VMB.BACKUP_STORAGE
WHERE PROTECTION_STATE = 'Protected'
GROUP BY 1, 2;

-- 5.6 Resource group owners. Flaw: inner joins, so groups with no or an unknown
--     ASSET_GROUP_ID (unowned cloud resources) silently drop out.
CREATE OR REPLACE VIEW ZONTIQUE_LEGACY.RPT.V_RG_OWNERS AS
SELECT rg.ASSET_NAME AS RESOURCE_GROUP, rg.ENVIRONMENT, app.ASSET_NAME AS APPLICATION,
       app.APPLICATION_CODE, app.DEPARTMENT, app.COST_CENTER
FROM ZONTIQUE_LEGACY.CMDB.ASSETS rg
JOIN ZONTIQUE_LEGACY.CMDB.ASSET_GROUPS g ON g.ASSET_GROUP_ID = rg.ASSET_GROUP_ID
JOIN ZONTIQUE_LEGACY.CMDB.ASSETS app ON app.ASSET_ID = g.APPLICATION_ASSET_ID
WHERE rg.ASSET_TYPE = 'AzureResourceGroup';

GRANT SELECT ON ALL VIEWS IN SCHEMA ZONTIQUE_LEGACY.RPT TO ROLE LEGACY_REPORT_ROLE;


-- =====================================================================
-- PART 6: checks
-- Expected: FOCUS_COST 45,051 / 207,755.81 | ASSETS 123 | ASSET_GROUPS 20 |
-- BUDGET 180 / 3,000,000.00 | BACKUP_JOBS 3,128 rows, 2,712 jobs, 59 files |
-- BACKUP_STORAGE 132 / 6,280.05 | legacy views: V_COST_BY_APP 186,500.36,
-- V_BACKUP_COST_BY_VM 5,771.45 (the 508.60 of orphaned backups is missing)
-- =====================================================================
SELECT 'COST.FOCUS_COST' AS T, COUNT(*) AS ROWS_, SUM(TRY_TO_DOUBLE(BILLEDCOST)) AS AMOUNT FROM ZONTIQUE_LEGACY.COST.FOCUS_COST
UNION ALL SELECT 'CMDB.ASSETS', COUNT(*), NULL FROM ZONTIQUE_LEGACY.CMDB.ASSETS
UNION ALL SELECT 'CMDB.ASSET_GROUPS', COUNT(*), NULL FROM ZONTIQUE_LEGACY.CMDB.ASSET_GROUPS
UNION ALL SELECT 'FIN.BUDGET', COUNT(*), SUM(TRY_TO_DOUBLE(BUDGET_COST)) FROM ZONTIQUE_LEGACY.FIN.BUDGET
UNION ALL SELECT 'VMB.BACKUP_JOBS', COUNT(*), NULL FROM ZONTIQUE_LEGACY.VMB.BACKUP_JOBS
UNION ALL SELECT 'VMB.BACKUP_STORAGE', COUNT(*), SUM(TRY_TO_DOUBLE(STORAGE_COST_USD)) FROM ZONTIQUE_LEGACY.VMB.BACKUP_STORAGE
UNION ALL SELECT 'RPT.V_COST_BY_APP', COUNT(*), SUM(TOTAL_COST_USD) FROM ZONTIQUE_LEGACY.RPT.V_COST_BY_APP
UNION ALL SELECT 'RPT.V_BACKUP_COST_BY_VM', COUNT(*), SUM(STORAGE_COST_USD) FROM ZONTIQUE_LEGACY.RPT.V_BACKUP_COST_BY_VM;

SELECT COUNT(DISTINCT JOB_ID) AS UNIQUE_JOBS, COUNT(DISTINCT _SOURCE_FILE) AS FILES FROM ZONTIQUE_LEGACY.VMB.BACKUP_JOBS;

